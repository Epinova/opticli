/**
 * Options the generated methods don't take: the output formats (the client always asks for JSON), a sealed run (only
 * the user, at a terminal) and a foreground serve (it runs until stopped).
 */
export const leftOutOptions = { '*': ['--text', '--jsonl'], apply: ['--seal'], serve: ['--foreground'] };

/** Global options the client sets itself (`OptiCli`'s `project` and `profile`), or that only change the output's format. */
export const clientGlobalOptions = ['--json', '--text', '--project', '--profile'];

const here = dirname(fileURLToPath(import.meta.url));
const header = (version) =>
  `// Generated by npm/scripts/generate.mjs from opticli ${version} (\`opticli schema --json\`). Don't edit: change the CLI\n` +
  `// or npm/scripts/overrides.mjs, and run \`npm run generate\`.\n`;

/** The TypeScript of `schema` (the `data` of `opticli schema --json`): `{ types, commands }`. */
export function generate(schema) {
  const defs = schema.$defs;
  const commands = include.map((path) => command(schema, path));
  const used = new Set();
  const typeOf = typeMapper(defs, used);

  const commandsTs = commandsFile(schema, commands, typeOf, used);
  const typesTs = typesFile(schema, reachable(defs, used), typeOf);
  return { types: typesTs, commands: commandsTs };
}

// The commands: their arguments, options and modes, as the methods take them.

function command(schema, path) {
  const found = schema.commands.find((c) => c.path.join(' ') === path);
  if (!found) throw new Error(`include: no command '${path}' in the schema.`);
  if (found.raw && !found.result) throw new Error(`include: '${path}' prints no JSON.`);
  const leftOut = new Set([...leftOutOptions['*'], ...(leftOutOptions[path] ?? [])]);
  for (const name of leftOutOptions[path] ?? []) {
    if (!found.options.some((o) => o.name === name)) throw new Error(`leftOutOptions: '${path}' has no ${name}.`);
  }
  const names = overrides.argumentNames[path] ?? {};
  const args = found.arguments.map((a) => ({
    ...a,
    key: identifier(names[a.name] ?? camel(a.name), `${path}'s argument ${a.name}`),
    array: a.type.type === 'array',
    // Required arguments are parameters; an optional one (a list of Name=value pairs, a project to list) is an option.
    inOptions: a.minimum === 0,
  }));
  const options = found.options.filter((o) => !leftOut.has(o.name)).map((o) => ({ ...o, key: camel(o.name) }));
  const keys = new Map();
  for (const entry of [...args.filter((a) => a.inOptions), ...options, ...commonOptions(schema)]) {
    if (keys.has(entry.key)) throw new Error(`'${path}': ${entry.name} and ${keys.get(entry.key)} are both '${entry.key}'.`);
    keys.set(entry.key, entry.name);
  }
  const method = camel(found.path.join('-'));
  const modes = (found.modes ?? []).map((m) => ({ ...m, alternatives: alternatives(m.when, args, options, path) })).filter((m) => m.alternatives.length > 0);
  if (found.lists && [found, ...modes].some((m) => m.result?.type !== 'array')) throw new Error(`'${path}' lists, but its result isn't an array.`);
  return {
    path,
    words: found.path,
    method,
    optionsType: `${pascal(method)}Options`,
    description: found.description,
    args,
    options,
    writes: found.writes,
    lists: found.lists,
    result: found.result,
    modes,
  };
}

/** The global options a method takes in its options object (`db`, `connection`, `connectionName`). */
function commonOptions(schema) {
  return schema.globalOptions.filter((o) => !clientGlobalOptions.includes(o.name)).map((o) => ({ ...o, key: camel(o.name) }));
}

/**
 * A mode's condition as the options object's narrowing: one alternative per way it holds (`anyOf`), each `{ key, type,
 * not }`: the property's type when it holds, and when it doesn't; for an option's values, `values` and the option's
 * `all` instead of `not`. Conditions on options the methods don't take are left out, and with them a mode that has no
 * other.
 */
function alternatives(when, args, options, path) {
  if (when.anyOf) return when.anyOf.flatMap((w) => alternatives(w, args, options, path));
  if (when.argument) {
    const arg = args.find((a) => a.name === when.argument);
    if (!arg) throw new Error(`'${path}': a mode depends on the argument ${when.argument}, which the schema doesn't describe.`);
    if (!arg.inOptions) throw new Error(`'${path}': a mode depends on the required argument ${when.argument}.`);
    return [{ key: arg.key, values: null, type: arg.array ? 'readonly [string, ...string[]]' : 'string', not: arg.array ? 'readonly []' : 'undefined' }];
  }
  const option = options.find((o) => o.name === when.option);
  if (!option) return [];
  if (when.values) return [{ key: option.key, values: when.values, all: option.type.enum, type: when.values.map(literal).join(' | ') }];
  const t = option.type;
  if (t.type === 'boolean') return [{ key: option.key, values: null, type: 'true', not: 'false' }];
  if (t.type === 'array') return [{ key: option.key, values: null, type: `readonly [${scalar(t.items)}, ...${scalar(t.items)}[]]`, not: 'readonly []' }];
  return [{ key: option.key, values: null, type: scalar(t), not: 'undefined' }];
}

/**
 * The fallback's narrowing: no mode's condition holds. Per key: the values no mode names (for an option with a fixed
 * set), else what `not` says. Null when one of them can't be said in TypeScript.
 */
function fallbackNarrowing(modes) {
  const byKey = new Map();
  for (const alt of modes.flatMap((m) => m.alternatives)) {
    const list = byKey.get(alt.key) ?? [];
    list.push(alt);
    byKey.set(alt.key, list);
  }
  const parts = [];
  for (const [key, alts] of byKey) {
    if (alts.every((a) => a.values)) {
      if (!alts[0].all) return null;
      const named = new Set(alts.flatMap((a) => a.values));
      const rest = alts[0].all.filter((v) => !named.has(v));
      parts.push(`${key}?: ${rest.length ? rest.map(literal).join(' | ') : 'never'}`);
    } else if (alts.every((a) => !a.values && a.not === alts[0].not)) {
      parts.push(`${key}?: ${alts[0].not}`);
    } else {
      return null;
    }
  }
  return `{ ${parts.join('; ')} }`;
}

// Types.

function typeMapper(defs, used) {
  const typeOf = (schema, place) => {
    if (place && overrides.properties[place]) return overrides.properties[place];
    if (schema === true || schema == null) return 'unknown';
    if (schema.$ref) {
      const name = schema.$ref.replace('#/$defs/', '');
      if (!defs[name]) throw new Error(`No definition ${name}.`);
      used.add(name);
      return name;
    }
    if (schema.anyOf) return union(schema.anyOf.map((s) => typeOf(s)));
    if (schema.const !== undefined) return literal(schema.const);
    if (schema['x-dynamic']) return schema.type === 'object' ? 'Record<string, unknown>' : schema.type === 'array' ? 'unknown[]' : 'unknown';
    if (schema.enum) return schema.enum.map(literal).join(' | ');
    switch (schema.type) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array':
        return array(typeOf(schema.items));
      case 'object':
        return `Record<string, ${schema.additionalProperties ? typeOf(schema.additionalProperties) : 'unknown'}>`;
      default:
        throw new Error(`Can't type ${JSON.stringify(schema)}.`);
    }
  };
  return typeOf;
}

/** A union; `string` beside other values (an open value set) becomes `(string & {})`, so the known ones still complete. */
function union(members) {
  const unique = [...new Set(members)];
  const open = unique.includes('string') && unique.some((m) => m !== 'string' && m !== 'null');
  return unique.map((m) => (open && m === 'string' ? '(string & {})' : m)).join(' | ');
}

const array = (type) => (/[ |&]/.test(type) ? `(${type})[]` : `${type}[]`);
const literal = (value) => (typeof value === 'string' ? `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : String(value));
const scalar = (t) => (t.enum ? t.enum.map(literal).join(' | ') : t.type === 'integer' || t.type === 'number' ? 'number' : t.type === 'boolean' ? 'boolean' : 'string');

/** Every definition the generated commands' results reach, by name. */
function reachable(defs, used) {
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    walk(defs[name], name);
  };
  const walk = (schema, owner, property) => {
    if (!schema || typeof schema !== 'object') return;
    if (property && overrides.properties[`${owner}.${property}`]) return;
    if (schema.$ref) visit(schema.$ref.replace('#/$defs/', ''));
    for (const s of schema.anyOf ?? []) walk(s, owner);
    if (schema.items) walk(schema.items, owner);
    if (typeof schema.additionalProperties === 'object') walk(schema.additionalProperties, owner);
    for (const [name, s] of Object.entries(schema.properties ?? {})) walk(s, owner, name);
  };
  for (const name of used) visit(name);
  return [...seen].sort();
}

function typesFile(schema, names, typeOf) {
  const defs = schema.$defs;
  for (const place of Object.keys(overrides.properties)) {
    const [type, property] = place.split('.');
    if (!defs[type]?.properties?.[property]) throw new Error(`overrides.properties: no ${place} in the schema.`);
  }
  for (const [type, generic] of Object.entries(overrides.generics)) {
    for (const property of Object.keys(generic.properties)) {
      if (!defs[type]?.properties?.[property]) throw new Error(`overrides.generics: no ${type}.${property} in the schema.`);
    }
  }
  const declared = [...overrides.declarations.matchAll(/^export (?:type|interface) (\w+)/gm)].map((m) => m[1]);
  const clash = declared.find((d) => defs[d]);
  if (clash) throw new Error(`overrides.declarations: ${clash} is also a type in the schema.`);

  let out = `${header(schema.opticli)}//\n// The result types of the generated commands (commands.ts), as opticli prints them: a property that may be absent is\n// optional (opticli leaves nulls out). Named as in opticli's C# code; a name doesn't change once published.\n`;
  out += overrides.declarations;
  for (const name of names) {
    const def = defs[name];
    out += `\n${doc(def.description, '')}`;
    if (def.enum) {
      out += `export type ${name} = ${def.enum.map(literal).join(' | ')};\n`;
    } else if (def.anyOf) {
      out += `export type ${name} = ${union(def.anyOf.map((s) => typeOf(s)))};\n`;
    } else if (def.type === 'object') {
      const generic = overrides.generics[name];
      out += `export interface ${name}${generic ? `<${generic.parameters}>` : ''} {\n`;
      const required = new Set(def.required ?? []);
      for (const [property, s] of Object.entries(def.properties)) {
        const type = generic?.properties[property] ?? typeOf(s, `${name}.${property}`);
        out += doc(s.description, '  ');
        out += `  ${key(property)}${required.has(property) ? '' : '?'}: ${type};\n`;
      }
      out += '}\n';
    } else {
      throw new Error(`Can't declare ${name}: ${JSON.stringify(def)}.`);
    }
  }
  return out;
}

// Commands.

function commandsFile(schema, commands, typeOf, used) {
  const common = commonOptions(schema);
  const optionTypes = [];
  const specs = [];
  const asyncMethods = [];
  const syncMethods = [];
  const methodNames = new Set();
  for (const c of commands) {
    for (const name of [c.method, ...(c.lists ? [`${c.method}All`] : [])]) {
      if (methodNames.has(name)) throw new Error(`Two methods are named ${name}.`);
      methodNames.add(name);
    }
    if (schema.$defs[c.optionsType]) throw new Error(`${c.optionsType} is also a type in the schema.`);
    optionTypes.push(optionsInterface(c));
    specs.push(`  ${key(c.method)}: {${[...c.args.filter((a) => a.inOptions).map((a) => ` ${a.key}: { argument: true }`), ...[...c.options, ...common].map((o) => ` ${o.key}: ${o.explicitFalse ? `{ flag: '${o.name}', explicitFalse: true }` : `'${o.name}'`}`)].join(',')} },`);
    asyncMethods.push(methods(c, typeOf, false));
    syncMethods.push(methods(c, typeOf, true));
  }
  for (const name of Object.keys(overrides.methods)) {
    if (!commands.some((c) => c.method === name)) throw new Error(`overrides.methods: no generated method ${name}.`);
  }
  for (const name of Object.keys(overrides.options)) {
    if (!commands.some((c) => c.options.some((o) => o.name === name))) throw new Error(`overrides.options: no generated command has ${name}.`);
  }
  for (const path of Object.keys(overrides.timeouts)) {
    if (!commands.some((c) => c.path === path)) throw new Error(`overrides.timeouts: '${path}' isn't generated.`);
  }
  for (const [path, names] of Object.entries(overrides.argumentNames)) {
    const c = commands.find((x) => x.path === path);
    if (!c || Object.keys(names).some((n) => !c.args.some((a) => a.name === n))) throw new Error(`overrides.argumentNames: '${path}' has no such argument.`);
  }

  const names = [...new Set([...used, ...Object.values(overrides.methods).flatMap((m) => m.imports ?? [])])].sort();
  return `${header(schema.opticli)}//
// One method per opticli command, in two classes: OptiCliCommands (async) and OptiCliCommandsSync (blocking, for code
// that can't await). Each runs \`opticli <command> <arguments> <options>\` through a runner, which adds --json and the
// project, and returns the envelope's data; list commands also have an iterator over every page (\`findAll\`).
import type { ${overrides.handWrittenImports.join(', ')} } from '../types.ts';
import type {
${names.map((n) => `  ${n},`).join('\n')}
} from './types.ts';

/** How one call runs. */
export interface CallOptions {
  /** Text for stdin (\`apply -\`, \`users add --password-stdin\`). */
  input?: string;
  /** Working directory for this call. */
  cwd?: string;
  /** How long to wait for opticli to answer. */
  timeoutMs?: number;
}

/** What a runner returns: the envelope of a successful command (\`ok: true\`); \`meta.next\` is a list's next page. */
export interface RunResult<T> {
  data: T;
  meta?: { next?: string };
}

/**
 * Runs \`opticli\` with these arguments (and \`--json\`), and returns the envelope; throws for \`ok: false\`. OptiCli's
 * \`run\` is one.
 */
export interface CommandRunner {
  run<T>(args: readonly string[], options?: CallOptions): Promise<RunResult<T>>;
}

/** As CommandRunner, blocking until opticli exits. */
export interface CommandRunnerSync {
  runSync<T>(args: readonly string[], options?: CallOptions): RunResult<T>;
}

/** Options every command takes: another of the project's databases, or a connection string. */
export interface CommonOptions {
${common.map((o) => optionProperty(o)).join('')}}

${optionTypes.join('\n')}
type Flag = string | { readonly flag: string; readonly explicitFalse: true } | { readonly argument: true };

/** Each method's options object: property → the option it is (or an argument, for an optional one). */
const specs: Readonly<Record<string, Readonly<Record<string, Flag>>>> = {
${specs.join('\n')}
};

/**
 * The command line: the command, its arguments, then its options. A flag is given for true; a three-state flag
 * (\`explicitFalse\`) is \`--name false\` for false. An array repeats the option; an object is sent as JSON.
 */
function argv(command: readonly string[], args: readonly (string | readonly string[])[], options: object | undefined, spec: Readonly<Record<string, Flag>>): string[] {
  const line = [...command, ...args.flat()];
  const given = (options ?? {}) as Record<string, unknown>;
  for (const name of Object.keys(given)) {
    if (!(name in spec)) throw new TypeError(\`opticli \${command.join(' ')} has no option '\${name}'.\`);
  }
  const flags: string[] = [];
  for (const [name, flag] of Object.entries(spec)) {
    const value = given[name];
    if (value === undefined || value === null) continue;
    if (typeof flag === 'object' && 'argument' in flag) {
      line.push(...(Array.isArray(value) ? value.map(String) : [String(value)]));
      continue;
    }
    const option = typeof flag === 'string' ? flag : flag.flag;
    if (typeof value === 'boolean') {
      if (value) flags.push(option);
      else if (typeof flag === 'object') flags.push(option, 'false');
    } else if (Array.isArray(value)) {
      for (const item of value) flags.push(option, String(item));
    } else if (typeof value === 'object') {
      flags.push(option, JSON.stringify(value));
    } else {
      flags.push(option, String(value));
    }
  }
  return [...line, ...flags];
}

/** opticli's commands, each returning the command's \`data\`. Prefer these to OptiCliCommandsSync wherever you can await. */
export class OptiCliCommands {
  readonly #runner: CommandRunner;

  constructor(runner: CommandRunner) {
    this.#runner = runner;
  }

  async #data<T>(args: readonly string[], call?: CallOptions): Promise<T> {
    return (await this.#runner.run<T>(args, call)).data;
  }

  async *#all<T>(args: readonly string[], call?: CallOptions): AsyncGenerator<T, void, undefined> {
    let page = await this.#runner.run<T[]>(args, call);
    yield* page.data;
    while (page.meta?.next) {
      page = await this.#runner.run<T[]>([...args, '--cursor', page.meta.next], call);
      yield* page.data;
    }
  }
${asyncMethods.join('')}}

/**
 * opticli's commands, blocking: each call waits for opticli to exit (a read takes about a second, a write longer), and
 * nothing else in the process runs meanwhile. For code that can't await, such as building \`projects\` in a
 * \`playwright.config\`; everywhere else, use OptiCliCommands.
 */
export class OptiCliCommandsSync {
  readonly #runner: CommandRunnerSync;

  constructor(runner: CommandRunnerSync) {
    this.#runner = runner;
  }

  #data<T>(args: readonly string[], call?: CallOptions): T {
    return this.#runner.runSync<T>(args, call).data;
  }

  *#all<T>(args: readonly string[], call?: CallOptions): Generator<T, void, undefined> {
    let page = this.#runner.runSync<T[]>(args, call);
    yield* page.data;
    while (page.meta?.next) {
      page = this.#runner.runSync<T[]>([...args, '--cursor', page.meta.next], call);
      yield* page.data;
    }
  }
${syncMethods.join('')}}
`;
}

function optionsInterface(c) {
  let out = `/** Options of \`opticli ${c.path}\`. */\nexport interface ${c.optionsType} extends CommonOptions {\n`;
  for (const a of c.args.filter((x) => x.inOptions)) {
    const type = a.array ? `readonly ${scalar(a.type.items)}[]` : scalar(a.type);
    out += doc(`${a.description ?? ''}${a.description ? ' ' : ''}(The argument \`${a.helpName ?? a.name}\`.)`, '  ');
    out += `  ${key(a.key)}?: ${type};\n`;
  }
  for (const o of c.options) out += optionProperty(o);
  return `${out}}\n`;
}

function optionProperty(o) {
  const override = overrides.options[o.name];
  let type;
  if (override) type = override.type;
  else if (o.type.type === 'array') type = `readonly ${scalar(o.type.items).includes(' ') ? `(${scalar(o.type.items)})` : scalar(o.type.items)}[]`;
  else type = scalar(o.type);
  const notes = [override?.description ?? o.description];
  if (o.explicitFalse) notes.push(`\`false\` passes \`${o.name} false\`; left out, the setting saved for the project decides.`);
  let text = notes.filter(Boolean).join(' ');
  if (o.default !== undefined && o.type.type !== 'boolean') text += `\n@defaultValue \`${JSON.stringify(o.default)}\``;
  return `${doc(text, '  ')}  ${key(o.key)}${o.required ? '' : '?'}: ${type};\n`;
}

/** The method (and for a list, its iterator), with an overload per mode. */
function methods(c, typeOf, sync) {
  const params = c.args.filter((a) => !a.inOptions).map((a) => `${a.key}: ${a.array ? `readonly ${scalar(a.type.items)}[]` : scalar(a.type)}`);
  const positional = `[${c.args.filter((a) => !a.inOptions).map((a) => a.key).join(', ')}]`;
  const optionsRequired = c.options.some((o) => o.required);
  const custom = overrides.methods[c.method];
  const typeParameters = custom ? `<${custom.typeParameters}>` : '';
  const timeout = overrides.timeouts[c.path];
  const call = timeout ? `{ ...call, timeoutMs: call?.timeoutMs ?? ${timeout} }` : 'call';
  const words = `[${c.words.map((w) => literal(w)).join(', ')}]`;
  const argvCall = `argv(${words}, ${positional}, options, specs.${c.method})`;
  const wrap = (t) => (sync ? t : `Promise<${t}>`);
  const iterator = (t) => (sync ? `Generator<${t}, void, undefined>` : `AsyncGenerator<${t}, void, undefined>`);

  const signatures = overloads(c, typeOf, custom);
  const paramDocs = c.args.filter((a) => !a.inOptions).map((a) => `@param ${a.key} - ${a.description ?? a.name}`);
  let out = '';
  const many = signatures.length > 1;
  // Async methods are async, so a wrong option rejects rather than throws.
  const modifier = sync ? '' : 'async ';
  for (const s of signatures) {
    const optionsParam = `options${s.required || optionsRequired ? '' : '?'}: ${s.options(c.optionsType)}`;
    // The sync class repeats only the first line: the async method has the whole description.
    const first = firstSentence(describe(c, false));
    const text = sync ? `${first}${s.writes && !first.includes('opticli serve') ? ' Writes: needs the site running (`opticli serve`).' : ''}\nBlocks until opticli exits; see \`OptiCliCommands.${c.method}\`.` : describe(c, s.writes);
    out += `\n${doc([text, ...paramDocs].join('\n'), '  ')}`;
    out += `  ${many ? '' : modifier}${key(c.method)}${typeParameters}(${[...params, optionsParam, 'call?: CallOptions'].join(', ')}): ${wrap(s.result)}${many ? ';' : ' {'}\n`;
  }
  const resultType = many ? 'any' : signatures[0].result;
  if (many) {
    out += `  ${modifier}${key(c.method)}(${[...params, `options${optionsRequired ? '' : '?'}: ${c.optionsType}`, 'call?: CallOptions'].join(', ')}): ${wrap('any')} {\n`;
  }
  out += `    return this.#data<${resultType}>(${argvCall}, ${call});\n  }\n`;

  if (c.lists) {
    const all = `${c.method}All`;
    const cursorless = `Omit<${c.optionsType}, 'cursor'>`;
    for (const s of signatures) {
      const optionsParam = `options${s.required || optionsRequired ? '' : '?'}: ${s.options(cursorless)}`;
      out += `\n${doc([`Every page of \`${c.method}\`, one call per page (\`limit\` is the page size): ${firstSentence(c.description)}`, ...paramDocs].join('\n'), '  ')}`;
      out += `  ${all}(${[...params, optionsParam, 'call?: CallOptions'].join(', ')}): ${iterator(s.item)}${many ? ';' : ' {'}\n`;
    }
    if (many) out += `  ${all}(${[...params, `options${optionsRequired ? '' : '?'}: ${cursorless}`, 'call?: CallOptions'].join(', ')}): ${iterator('any')} {\n`;
    out += `    return this.#all<${many ? 'any' : signatures[0].item}>(${argvCall}, ${call});\n  }\n`;
  }
  return out;
}

/**
 * The method's signatures: one per mode (and per way its condition holds), then the fallback narrowed to options that
 * pick no mode, then any options with every result possible; first match wins, as when opticli picks the mode.
 */
function overloads(c, typeOf, custom) {
  const item = (result) => (c.lists ? typeOf(result.items) : undefined);
  if (custom) {
    typeOf(c.result);
    return [{ options: (t) => t, result: custom.result, writes: c.writes, required: false }];
  }
  const fallback = { options: (t) => t, result: typeOf(c.result), item: item(c.result), writes: c.writes, required: false };
  if (c.modes.length === 0) return [fallback];
  const signatures = [];
  for (const mode of c.modes) {
    for (const alt of mode.alternatives) {
      signatures.push({ options: (t) => `${t} & { ${alt.key}: ${alt.type} }`, result: typeOf(mode.result), item: item(mode.result), writes: mode.writes, required: true });
    }
  }
  const narrowed = fallbackNarrowing(c.modes);
  if (narrowed) signatures.push({ ...fallback, options: (t) => `${t} & ${narrowed}` });
  const all = [...c.modes.map((m) => m.result), c.result];
  signatures.push({
    options: (t) => t,
    result: union(all.map((r) => typeOf(r))),
    item: c.lists ? union(all.map((r) => typeOf(r.items))) : undefined,
    writes: c.writes || c.modes.some((m) => m.writes),
    required: false,
  });
  return signatures;
}

function describe(c, writes) {
  const text = c.description ?? `\`opticli ${c.path}\`.`;
  return writes && !text.includes('opticli serve') ? `${text}\nWrites: needs the site running (\`opticli serve\`).` : text;
}

/** The description's first sentence (up to a full stop that isn't in "e.g.", "i.e." or "incl."), on one line. */
const firstSentence = (text) => {
  const flat = (text ?? '').replace(/\s+/g, ' ').trim();
  return flat.match(/^.*?(?<!\be\.g|\bi\.e|\bincl)\.(?=\s|$)/)?.[0] ?? flat;
};

// Names and comments.

const camel = (name) =>
  name
    .replace(/^-+/, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part, i) => (i === 0 ? part[0].toLowerCase() + part.slice(1) : part[0].toUpperCase() + part.slice(1)))
    .join('');
const pascal = (name) => name[0].toUpperCase() + name.slice(1);
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

const reserved = new Set(['break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'null', 'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield', 'let', 'static', 'implements', 'interface', 'package', 'private', 'protected', 'public', 'await', 'options', 'call']);
function identifier(name, what) {
  if (!/^[A-Za-z_$][\w$]*$/.test(name) || reserved.has(name)) throw new Error(`${what} isn't a usable parameter name (${name}): add it to overrides.argumentNames.`);
  return name;
}

/** A TSDoc comment: a line starting with `@` that isn't a tag is escaped, and so is a comment's end. */
function doc(text, indent) {
  if (!text) return '';
  const lines = text
    .replace(/\*\//g, '*\\/')
    .split('\n')
    .map((line) => (/^\s*@/.test(line) && !/^@(param|defaultValue)\b/.test(line) ? line.replace('@', '\\@') : line).trimEnd());
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

// Running it.

/** How to run opticli: $OPTICLI, else the newest build of this checkout's src/OptiCli. */
function opticli() {
  const bin = process.env.OPTICLI;
  if (bin) return bin.endsWith('.dll') ? ['dotnet', resolve(bin)] : [bin];
  const builds = ['Debug', 'Release']
    .map((c) => join(here, '..', '..', 'src', 'OptiCli', 'bin', c, 'net8.0', 'opticli.dll'))
    .filter((f) => existsSync(f))
    .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);
  if (!builds.length) throw new Error('No opticli build: run `dotnet build src/OptiCli` first, or set OPTICLI.');
  return ['dotnet', builds[0]];
}

function main() {
  const [program, ...prefix] = opticli();
  const output = execFileSync(program, [...prefix, 'schema', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const envelope = JSON.parse(output);
  if (!envelope.ok) throw new Error(`opticli schema failed: ${JSON.stringify(envelope.error)}`);
  const { types, commands } = generate(envelope.data);
  const out = join(here, '..', 'src', 'generated');
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'types.ts'), types);
  writeFileSync(join(out, 'commands.ts'), commands);
  console.log(`src/generated: ${include.length} commands from opticli ${envelope.data.opticli} (${[program, ...prefix].join(' ')})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
