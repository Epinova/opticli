// Generates src/generated/types.ts and src/generated/commands.ts from opticli's own description of its commands
// (`opticli schema --json`): one method per command in `include`, its options as an object, its result type, and an
// iterator over every page for list commands; async (OptiCliCommands) and sync (OptiCliCommandsSync).
//
// opticli: $OPTICLI (an executable, or a checkout's opticli.dll), else this checkout's newest build of src/OptiCli.
// Run `npm run generate` after a change to a command, its options or its result types; CI fails when the committed files
// differ from what this writes.
